import { formatLine } from '../openings/format';
import { INITIAL_FEN, playLine } from '../position';
import type { NameNode, NameTree } from './names';

const SYMBOL = { w: '○', b: '●', both: '◐' } as const;
const SIDE = { w: 'White', b: 'Black', both: 'Both' } as const;

/**
 * The name tree as Markdown (`docs/openings.md`): a heading per opening (ECO, owner, moves), its
 * variations as nested bullets (ECO, side, moves). A group without a position of its own is marked
 * "group"; a dataset name that differs from the key is shown after "dataset:".
 */
export function formatOpeningList(tree: NameTree): string {
  const all = [...tree.all()];
  const groups = all.filter((n) => !n.own).length;
  const count = (n: number) => n.toLocaleString('en-US');
  const moves = (n: NameNode) => formatLine(playLine(INITIAL_FEN, n.ucis)?.san ?? []);
  const extra = (n: NameNode) =>
    (n.own ? '' : ' · group') + (n.name && n.name !== n.key ? ` · dataset: \`${n.name}\`` : '');

  const out = [
    '# Opening names',
    '',
    'Generated by `pnpm build:openings` from `data/openings/*.tsv` through `buildNameTree`',
    '(`packages/core/src/lab/names.ts`, ADR 012). Do not edit by hand.',
    '',
    `${count(tree.roots.length)} openings, ${count(all.length)} levels, ${count(groups)} of them groups.`,
    'Openings and variations are sorted by popularity (dataset lines through their position).',
    'Each level: ECO · side (○ White, ● Black, ◐ both) · moves. A group has no position of its own:',
    'its ECO and moves are those of its most played variation. Variation keys are',
    '"Opening: Variation, Subvariation".',
  ];
  const bullets = (n: NameNode, depth: number): void => {
    for (const k of n.children) {
      const c = tree.get(k)!;
      const side = c.side ? SYMBOL[c.side] : '·';
      out.push(
        `${'  '.repeat(depth)}- **${c.label}** · ${c.eco} · ${side} · ${moves(c)}${extra(c)}`,
      );
      bullets(c, depth + 1);
    }
  };
  for (const k of tree.roots) {
    const n = tree.get(k)!;
    const owner = n.owner ?? n.side ?? 'w';
    out.push(
      '',
      `## ${n.key}`,
      '',
      `${n.eco} · ${SYMBOL[owner]} ${SIDE[owner]} · ${moves(n)}${extra(n)}`,
    );
    if (n.children.length) out.push('');
    bullets(n, 0);
  }
  return out.join('\n') + '\n';
}
